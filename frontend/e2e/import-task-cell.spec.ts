import {test,expect} from '@playwright/test';

test('upload remains unjudged until a configured MuJoCo task is run',async({page})=>{
  const errors:string[]=[];
  let streamedLiveFrame=false;
  page.on('pageerror',error=>errors.push(error.message));
  page.on('response',async response=>{if(response.url().includes('/task-trials/')&&new URL(response.url()).pathname.endsWith('/frames')&&response.status()===200){try{const update=await response.json();streamedLiveFrame ||= update.status==='task_running'&&update.frames.length>0;}catch{/* ignore unrelated response parsing */}}});
  await page.goto('/import');
  await expect(page.getByRole('button',{name:'Environment geometry',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Environment geometry',exact:true}).click();
  await page.getByLabel('Choose environment geometry').setInputFiles('../fixtures/imports/triangle.glb');
  await page.getByRole('button',{name:'Inspect geometry',exact:true}).click();
  await expect(page.getByRole('region',{name:'Imported static geometry preview'})).toBeVisible();
  await expect.poll(()=>page.evaluate(()=>(window as any).__vivacityImport?.physicsReady)).toBe(false);
  await page.getByRole('button',{name:'Robot or CAD',exact:true}).click();
  await page.getByLabel('Choose robot or CAD file').setInputFiles('../fixtures/imports/vivacity_sample_arm.xml');
  await page.getByRole('button',{name:'Stage in lab',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Ready to configure',exact:true})).toBeVisible();
  await expect(page.getByText('Nothing has been declared successful or failed yet.',{exact:true})).toBeVisible();
  await page.getByLabel('Environment').selectOption('tabletop');
  await page.getByLabel('Task').selectOption('reach');
  await page.getByLabel('Base placement').selectOption('bolted');
  await page.getByRole('button',{name:'Place in test cell',exact:true}).click();
  await expect(page.getByRole('button',{name:'Run configured task',exact:true})).toBeEnabled();
  await page.getByRole('button',{name:'Run configured task',exact:true}).click();
  await expect.poll(()=>streamedLiveFrame,{timeout:15000}).toBe(true);
  await expect(page.getByRole('img',{name:/3D MuJoCo workcell/})).toBeVisible({timeout:15000});
  await expect(page.locator('.import-scene-canvas canvas')).toBeVisible();
  await expect(page.getByRole('heading',{name:'Task succeeded',exact:true})).toBeVisible({timeout:60000});
  await expect(page.getByRole('heading',{name:'Configured MuJoCo task',exact:true})).toBeVisible();
  await expect.poll(()=>page.evaluate(()=>(window as any).__vivacityTaskTrial?.source)).toBe('measured_mujoco');
  await expect(page.getByText(/Joint and actuator health/)).toBeVisible();
  await page.getByRole('button',{name:/Inspect .* at its peak effort in the 3D workcell/}).first().click();
  await expect(page.getByRole('img',{name:/3D MuJoCo workcell/})).toHaveAttribute('data-highlight-body-id',/^[0-9]+$/);
  await expect(page.getByRole('button',{name:'Replay measured task'})).toBeVisible();
  await page.screenshot({path:'test-results/import-workcell-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await expect(page.getByRole('img',{name:/3D MuJoCo workcell/})).toBeVisible();
  await page.screenshot({path:'test-results/import-workcell-mobile.png',fullPage:true});
  await expect(page.getByText('Failure-model boundary:')).toBeVisible();
  await expect(page.getByRole('button',{name:'Import another asset',exact:true})).toBeVisible();
  expect(errors).toEqual([]);
});

